#!/usr/bin/env bash
#
# mayhem/build.sh — build pytz (zoneinfo compiled by the vendored IANA tz code) and the fuzz targets.
#
#  1. Upstream's own build (`make build`, NORMAL flags): builds tz/zic + tz/zdump, compiles the IANA
#     zone sources into build/etc/zoneinfo and generates the pytz package in build/dist. This is what
#     mayhem/test.sh tests and what the atheris target (fuzz_pytz) imports.
#  2. The sanitized fuzz build of the tz C code, out of tree into mayhem/out (gitignored):
#       libFuzzer: fuzz_tzfile, fuzz_tzstring, fuzz_strftime (localtime.c/strftime.c/asctime.c)
#       AFL (file-input CLIs that exit() on bad input): zic, zdump
#     plus a -standalone reproducer per libFuzzer harness, and the fuzz_pytz launcher.
set -euo pipefail

[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${SANITIZER_FLAGS=-fsanitize=address,undefined -fno-sanitize-recover=all -fno-omit-frame-pointer}"
: "${DEBUG_FLAGS:=-g -gdwarf-3}"
: "${CC:=clang}" ; : "${CXX:=clang++}" ; : "${LIB_FUZZING_ENGINE:=-fsanitize=fuzzer}"
: "${STANDALONE_FUZZ_MAIN:=/opt/mayhem/StandaloneFuzzTargetMain.c}"
: "${MAYHEM_JOBS:=$(nproc)}"
: "${COVERAGE_FLAGS=}"
export SANITIZER_FLAGS DEBUG_FLAGS CC CXX LIB_FUZZING_ENGINE MAYHEM_JOBS COVERAGE_FLAGS

cd "${SRC:-/mayhem}"
SRCDIR=$PWD

# 1) Upstream build with normal flags (idempotent: the .stamp-* files short-circuit a re-run).
env -u CFLAGS -u LDFLAGS make build PYTHON=python3 CC="$CC" \
  ${COVERAGE_FLAGS:+CFLAGS="$COVERAGE_FLAGS" LDFLAGS="$COVERAGE_FLAGS"}
test -x tz/zic && test -x tz/zdump && test -f build/dist/pytz/zoneinfo/Europe/London
# Upstream's `make test_zdump` data step: zdump(1) output for every zone 1902-2038 into zdump.out
# (gitignored), which mayhem/test.sh feeds to upstream's test_zdump.py. Only calls build/bin/zdump.
python3 gen_tests.py
test -s zdump.out

# 2) Sanitized fuzz build (DWARF 3) of the tz C code, out of tree.
OUT=$SRCDIR/mayhem/out
OBJ=$OUT/obj
mkdir -p "$OBJ/fuzz" "$OBJ/afl-zdump"
TZ_SRC=$SRCDIR/tz
# version.h / tzdir.h are generated by tz's Makefile in step 1.
COMMON="-O1 -I$TZ_SRC -I$SRCDIR/mayhem/harnesses"

$CXX $SANITIZER_FLAGS $DEBUG_FLAGS -c "$SRCDIR/mayhem/lsan_off.cc" -o "$OBJ/lsan_off.o"
$CC $SANITIZER_FLAGS $DEBUG_FLAGS -c "$STANDALONE_FUZZ_MAIN" -o "$OBJ/standalone_main.o"

# libFuzzer library objects (instrumented for coverage + sanitizers).
LIBOBJS=()
for f in localtime strftime asctime difftime; do
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link $COMMON -c "$TZ_SRC/$f.c" -o "$OBJ/fuzz/$f.o"
  LIBOBJS+=("$OBJ/fuzz/$f.o")
done
for h in fuzz_tzfile fuzz_tzstring fuzz_strftime; do
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS -fsanitize=fuzzer-no-link $COMMON -c "$SRCDIR/mayhem/harnesses/$h.c" -o "$OBJ/fuzz/$h.o"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS $LIB_FUZZING_ENGINE "$OBJ/fuzz/$h.o" "${LIBOBJS[@]}" "$OBJ/lsan_off.o" -o "$OUT/$h"
  $CC $SANITIZER_FLAGS $DEBUG_FLAGS "$OBJ/standalone_main.o" "$OBJ/fuzz/$h.o" "${LIBOBJS[@]}" "$OBJ/lsan_off.o" -o "$OUT/$h-standalone"
done

# AFL file-input CLIs (zic and zdump call exit() on bad input, so they are fuzzed as programs).
AFL_CC=${AFL_CC_BIN:-afl-clang-fast}
# zic: main renamed to zic_main and driven by mayhem/harnesses/zic_scratch.c, which gives every execution
# its own fresh `-d` output directory under $TMPDIR and removes it on exit (no state between inputs).
mkdir -p "$OBJ/afl-zic"
AFL_QUIET=1 $AFL_CC $SANITIZER_FLAGS $DEBUG_FLAGS $COMMON -Dmain=zic_main -c "$TZ_SRC/zic.c" -o "$OBJ/afl-zic/zic.o"
AFL_QUIET=1 $AFL_CC $SANITIZER_FLAGS $DEBUG_FLAGS $COMMON -c "$SRCDIR/mayhem/harnesses/zic_scratch.c" -o "$OBJ/afl-zic/zic_scratch.o"
AFL_QUIET=1 $AFL_CC $SANITIZER_FLAGS $DEBUG_FLAGS "$OBJ/afl-zic/zic_scratch.o" "$OBJ/afl-zic/zic.o" "$OBJ/lsan_off.o" -o "$OUT/zic"
# zdump: SUPPRESS_TZDIR (tz's documented build option) so a relative @@ path is opened as given.
ZOBJS=()
for f in zdump localtime strftime asctime; do
  AFL_QUIET=1 $AFL_CC $SANITIZER_FLAGS $DEBUG_FLAGS $COMMON -DSUPPRESS_TZDIR=1 -c "$TZ_SRC/$f.c" -o "$OBJ/afl-zdump/$f.o"
  ZOBJS+=("$OBJ/afl-zdump/$f.o")
done
AFL_QUIET=1 $AFL_CC $SANITIZER_FLAGS $DEBUG_FLAGS "${ZOBJS[@]}" "$OBJ/lsan_off.o" -o "$OUT/zdump"

# 3) Launcher for the OSS-Fuzz atheris harness (Mayhem needs an ELF cmd:).
$CC $DEBUG_FLAGS -DHARNESS_PY="\"$SRCDIR/mayhem/fuzz_pytz/fuzz_pytz.py\"" \
  "$SRCDIR/mayhem/fuzz_pytz/launcher.c" -o "$OUT/fuzz_pytz"

ls -l "$OUT"
