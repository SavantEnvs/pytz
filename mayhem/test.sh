#!/usr/bin/env bash
#
# mayhem/test.sh — RUN pytz's own unit tests and known-answer checks of the vendored IANA tz tools
# (all built by mayhem/build.sh with normal flags). exit 0 = pass. PATCH-grade oracle: after an agent patches the source, the grader
# rebuilds (build.sh) then runs this. DELETE this file if the repo has no meaningful tests.
#
# IMPORTANT:
#  * Must assert BEHAVIOR/OUTPUT, not just exit status. The oracle has to check asserted values /
#    golden-output diffs / known-answer results — so a PATCH that "fixes" a bug by making the program
#    exit(0) (or any no-op) FAILS here. Running inputs and checking only "exit 0 / didn't crash" is
#    NOT a functional test (it's trivially reward-hackable) — use the project's real assertion suite.
#  * Do NOT build here — mayhem/build.sh already compiled the test suite (with the project's normal
#    flags). This script only RUNS the pre-built tests and reports counts. If the test runner is
#    missing, that's a build.sh bug — fail loudly rather than silently rebuilding.
#  * REQUIRED OUTPUT — a CTRF (https://ctrf.io) summary so Mayhem/the PATCH grader reads the counts:
#      - writes a CTRF JSON report to ${CTRF_REPORT:-$SRC/ctrf-report.json}, and
#      - prints a one-line `CTRF {...}` marker to stdout (same JSON, compact).
#    Only `results.summary` (with tests/passed/failed/pending/skipped/other) is required.
#    Use the emit_ctrf helper below; it computes tests = passed+failed+skipped and sets the exit
#    code (0 iff failed==0). Map your framework's output to passed/failed/skipped.
set -uo pipefail
[ -n "${SOURCE_DATE_EPOCH:-}" ] || unset SOURCE_DATE_EPOCH
: "${MAYHEM_JOBS:=$(nproc)}"   # build parallelism; env-overridable, falls back to nproc (use -j"$MAYHEM_JOBS")
cd "$SRC"

# emit_ctrf <tool> <passed> <failed> [skipped] [pending] [other]
# Writes a CTRF report (file + stdout `CTRF {...}` marker) and returns non-zero iff failed>0.
emit_ctrf() {
  local tool="$1" passed="$2" failed="$3" skipped="${4:-0}" pending="${5:-0}" other="${6:-0}"
  local tests=$(( passed + failed + skipped + pending + other ))
  cat > "${CTRF_REPORT:-$SRC/ctrf-report.json}" <<JSON
{
  "results": {
    "tool": { "name": "$tool" },
    "summary": {
      "tests": $tests,
      "passed": $passed,
      "failed": $failed,
      "pending": $pending,
      "skipped": $skipped,
      "other": $other
    }
  }
}
JSON
  printf 'CTRF {"results":{"tool":{"name":"%s"},"summary":{"tests":%d,"passed":%d,"failed":%d,"pending":%d,"skipped":%d,"other":%d}}}\n' \
    "$tool" "$tests" "$passed" "$failed" "$pending" "$skipped" "$other"
  [ "$failed" -eq 0 ]
}

PASS=0; FAIL=0
ok()   { PASS=$((PASS+1)); echo "PASS: $1"; }
bad()  { FAIL=$((FAIL+1)); echo "FAIL: $1"; }

# 1) pytz's own unittest suites (src/pytz/tests, generated into build/dist by `make build`).
#    test_tzinfo/test_lazy/test_docs run from build/dist/pytz/tests (upstream `make test_*`);
#    test_zdump.py runs from the repo root against zdump.out (generated by build.sh via gen_tests.py).
TESTDIR=build/dist/pytz/tests
if [ ! -d "$TESTDIR" ]; then echo "missing $TESTDIR — run mayhem/build.sh first" >&2; emit_ctrf "pytz-unittest+tz-kat" 0 1; exit 1; fi
if [ ! -s zdump.out ]; then echo "missing zdump.out — run mayhem/build.sh first" >&2; emit_ctrf "pytz-unittest+tz-kat" 0 1; exit 1; fi
for ds in "$TESTDIR:test_tzinfo.py" "$TESTDIR:test_lazy.py" "$TESTDIR:test_docs.py" ".:test_zdump.py"; do
  dir=${ds%%:*}; suite=${ds#*:}
  out=$(cd "$dir" && python3 "$suite" 2>&1); rc=$?
  ran=$(printf '%s\n' "$out" | sed -n 's/^Ran \([0-9]*\) tests\{0,1\}.*/\1/p' | tail -1)
  f=$(printf '%s\n' "$out" | sed -n 's/.*failures=\([0-9]*\).*/\1/p' | tail -1)
  e=$(printf '%s\n' "$out" | sed -n 's/.*errors=\([0-9]*\).*/\1/p' | tail -1)
  ran=${ran:-0}; f=${f:-0}; e=${e:-0}
  nf=$((f+e))
  if [ "$ran" -eq 0 ] || { [ $rc -ne 0 ] && [ $nf -eq 0 ]; }; then
    printf '%s\n' "$out" | tail -20; bad "$suite (did not run cleanly, rc=$rc)"; continue
  fi
  [ $nf -gt 0 ] && printf '%s\n' "$out" | grep -E '^(FAIL|ERROR):' | head -20
  PASS=$((PASS + ran - nf)); FAIL=$((FAIL + nf))
  echo "$suite: ran=$ran failed=$nf"
done

# 2) Known-answer checks of the tz tools pytz's zoneinfo is built with (tz/zic, tz/zdump).
ZIC=tz/zic; ZDUMP=tz/zdump
for b in "$ZIC" "$ZDUMP"; do [ -x "$b" ] || { echo "missing $b — run mayhem/build.sh first" >&2; emit_ctrf "pytz-unittest+tz-kat" "$PASS" $((FAIL+1)); exit 1; }; done
T=$(mktemp -d "${TMPDIR:-/tmp}/pytz-test.XXXXXX"); trap 'rm -rf "$T"' EXIT
"$ZIC" -b fat -d "$T/zi" tz/europe tz/northamerica tz/etcetera >"$T/zic.log" 2>&1 \
  && [ -s "$T/zi/Europe/London" ] && ok "zic compiles europe/northamerica/etcetera" || bad "zic compiles europe/northamerica/etcetera"
head -c 5 "$T/zi/Europe/London" 2>/dev/null | grep -q '^TZif' && ok "zic output is TZif" || bad "zic output is TZif"
expect() { # name, command output file, expected line
  grep -qxF "$3" "$2" && ok "$1" || { bad "$1"; echo "  expected: $3"; head -5 "$2" | sed 's/^/  got: /'; }
}
"$ZDUMP" -v -c 2020,2021 "$T/zi/Europe/London" > "$T/lon" 2>&1
expect "zdump London 2020 spring-forward" "$T/lon" "$T/zi/Europe/London  Sun Mar 29 01:00:00 2020 UT = Sun Mar 29 02:00:00 2020 BST isdst=1 gmtoff=3600"
expect "zdump London 2020 fall-back"      "$T/lon" "$T/zi/Europe/London  Sun Oct 25 01:00:00 2020 UT = Sun Oct 25 01:00:00 2020 GMT isdst=0 gmtoff=0"
"$ZDUMP" -v -c 2024,2025 "$T/zi/America/New_York" > "$T/ny" 2>&1
expect "zdump New_York 2024 spring-forward" "$T/ny" "$T/zi/America/New_York  Sun Mar 10 07:00:00 2024 UT = Sun Mar 10 03:00:00 2024 EDT isdst=1 gmtoff=-14400"
"$ZDUMP" -v -c 2024,2025 'CET-1CEST,M3.5.0,M10.5.0/3' > "$T/posix" 2>&1
# (weekday after '=' deliberately not asserted for TZ-string zones: this tz snapshot prints it wrong)
grep -qF "CET-1CEST,M3.5.0,M10.5.0/3  Sun Mar 31 01:00:00 2024 UT = " "$T/posix" \
  && grep -qF "Mar 31 03:00:00 2024 CEST isdst=1 gmtoff=7200" "$T/posix" \
  && grep -qF "Oct 27 02:00:00 2024 CET isdst=0 gmtoff=3600" "$T/posix" \
  && ok "zdump POSIX TZ string rule" || { bad "zdump POSIX TZ string rule"; head -8 "$T/posix"; }
cmp -s "$T/zi/Europe/London" build/dist/pytz/zoneinfo/Europe/London && ok "pytz zoneinfo matches zic output" || bad "pytz zoneinfo matches zic output"

# 3) pytz end-to-end known answers through the generated package.
kat=$(cd build/dist && python3 -c '
import pytz, datetime
lon = pytz.timezone("Europe/London")
d = lon.localize(datetime.datetime(2020, 7, 1, 12, 0))
print(d.strftime("%Y-%m-%d %H:%M %Z%z"), d.astimezone(pytz.utc).strftime("%H:%M %Z"))
' 2>&1)
[ "$kat" = "2020-07-01 12:00 BST+0100 11:00 UTC" ] && ok "pytz localize Europe/London" || { bad "pytz localize Europe/London"; echo "  got: $kat"; }

emit_ctrf "pytz-unittest+tz-kat" "$PASS" "$FAIL"
